-- Catálogo TACO disponível para todo usuário, não só para o primeiro.
-- A tabela de referência guarda a seed uma única vez; cada conta recebe a
-- própria cópia em food_items (editável e apagável sem afetar as outras).

create table food_items_seed (
    name text primary key,
    reference_quantity numeric(8, 2) not null,
    reference_unit text not null check (reference_unit in ('g', 'ml', 'unidade', 'porcao', 'colher')),
    kcal numeric(7, 2) check (kcal is null or kcal >= 0),
    protein_g numeric(6, 2) check (protein_g is null or protein_g >= 0),
    carbs_g numeric(6, 2) check (carbs_g is null or carbs_g >= 0),
    fat_g numeric(6, 2) check (fat_g is null or fat_g >= 0)
);

