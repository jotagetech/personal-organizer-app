-- Copia a seed para um usuário. Não sobrescreve nome que ele já tenha no
-- catálogo, então pode rodar mais de uma vez sem duplicar.
create function seed_food_items_for_user(p_user_id uuid) returns void as $$
begin
    insert into food_items (
        user_id, name, reference_quantity, reference_unit, kcal, protein_g, carbs_g, fat_g, is_seed
    )
    select p_user_id, s.name, s.reference_quantity, s.reference_unit,
        s.kcal, s.protein_g, s.carbs_g, s.fat_g, true
    from food_items_seed s
    on conflict (user_id, lower(trim(name))) do nothing;
end;
$$ language plpgsql security definer set search_path = public;

revoke execute on function seed_food_items_for_user(uuid) from public, anon, authenticated;

create or replace function handle_new_user() returns trigger as $$
begin
    insert into user_settings (user_id) values (new.id);
    perform seed_food_items_for_user(new.id);
    return new;
end;
$$ language plpgsql security definer set search_path = public;

-- Contas que já existem sem nenhum item da seed recebem o catálogo agora.
-- Quem já tem a seed fica como está, preservando itens apagados ou editados.
select seed_food_items_for_user(u.id)
from auth.users u
where not exists (
    select 1 from food_items f where f.user_id = u.id and f.is_seed
);
